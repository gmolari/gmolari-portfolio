export type GlyphName = keyof typeof G;

export function Glyph({ name, size = 18, className }: { name: GlyphName; size?: number; className?: string }) {
  const rows = G[name];
  return (
    <svg viewBox="0 0 9 9" width={size} height={size} shapeRendering="crispEdges" className={className} aria-hidden="true">
      {rows.flatMap((r, y) =>
        [...r].map((c, x) =>
          c === "." ? null : (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={c === "+" ? "color-mix(in srgb, currentColor 45%, white)" : "currentColor"} />
          ),
        ),
      )}
    </svg>
  );
}
